  const LANGS = { en: "English", hi: "हिंदी", bn: "বাংলা" };
  const ORDER = ["en", "hi", "bn"];
  const SHORT = { en: "EN", hi: "हिं", bn: "বাং" };

  function getLang() {
    const l = (global.localStorage && global.localStorage.getItem("saathi_lang")) || "en";
    return I18N_DICT[l] ? l : "en";
  }
  function t(key, vars) {
    const lang = getLang();
    const d = I18N_DICT[lang] || {};
    let s = (key in d) ? d[key] : (EN[key] !== undefined ? EN[key] : key);
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  }
  function apply(lang) {
    if (!I18N_DICT[lang]) lang = "en";
    try { global.localStorage && global.localStorage.setItem("saathi_lang", lang); } catch (e) {}
    const doc = global.document;
    if (!doc) return lang;
    doc.documentElement.setAttribute("lang", lang === "hi" ? "hi" : lang === "bn" ? "bn" : "en");
    doc.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
    doc.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
    doc.querySelectorAll("[data-i18n-ph]").forEach(el => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
    doc.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
    doc.querySelectorAll("[data-i18n-title]").forEach(el => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
    doc.querySelectorAll(".lang-short").forEach(el => { el.textContent = SHORT[lang]; });
    if (typeof global.onLanguageApplied === "function") { try { global.onLanguageApplied(lang); } catch (e) {} }
    return lang;
  }
  function currentShort() { return SHORT[getLang()]; }

  var I18N_DICT = { en: EN };
  var I18N = { t: t, apply: apply, getLang: getLang, LANGS: LANGS, ORDER: ORDER, SHORT: SHORT, currentShort: currentShort, EN: EN, get DICT() { return I18N_DICT; } };
  function registerI18n(lang, dict) { I18N_DICT[lang] = Object.assign({}, EN, dict); }
